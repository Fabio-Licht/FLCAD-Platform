  static Iterable<CommandPresentationEntry> byType(
    CommandCatalogEntryType type,
  ) => entries.where((e) => e.type == type);

  static CommandPresentationEntry byId(String id) =>
      entries.firstWhere((e) => e.id == id);

  /// Search ordering for the compact palette. IDs participate only for
  /// diagnostics; the normal UI renders names and descriptions.
  static List<CommandPresentationEntry> search(String query) {
    final normalized = _normalize(query);
    if (normalized.isEmpty) return List<CommandPresentationEntry>.from(entries);
    final ranked = <({CommandPresentationEntry entry, int score})>[];
    for (final entry in entries) {
      final name = _normalize(entry.name);
      final category = _normalize(entry.category);
      final activity = _normalize(entry.activity);
      final description = _normalize(entry.description);
      final id = _normalize(entry.id);
      final aliases = entry.aliases.map(_normalize).toList(growable: false);
      var score = 0;
      if (name == normalized) {
        score = 1000;
      } else if (name.startsWith(normalized)) {
        score = 800;
      } else if (aliases.any((alias) => alias == normalized)) {
        score = 700;
      } else if (aliases.any((alias) => alias.startsWith(normalized))) {
        score = 600;
      } else if (category.startsWith(normalized) ||
          activity.startsWith(normalized)) {
        score = 500;
      } else if (description.contains(normalized) || id.contains(normalized)) {
        score = 300;
      }
      if (score > 0) ranked.add((entry: entry, score: score));
    }
    ranked.sort(
      (a, b) => b.score != a.score
          ? b.score.compareTo(a.score)
          : a.entry.name.compareTo(b.entry.name),
    );
    return ranked.map((value) => value.entry).toList(growable: false);
  }

  static String _normalize(String value) =>
      value.toLowerCase().trim().replaceAll(RegExp(r'\s+'), '');

