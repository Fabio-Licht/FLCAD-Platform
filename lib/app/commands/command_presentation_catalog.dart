/// Presentation metadata for commands and modeling capabilities.
///
/// This catalog is intentionally passive: it does not resolve, execute, or
/// authorize commands. Technical identifiers remain owned by their existing
/// registries and controllers.
enum CommandCatalogEntryType {
  command,
  contextualAction,
  workspace,
  capability,
}

enum CommandCatalogSource {
  commandRegistry,
  operationalController,
  capabilityRegistry,
}

enum CommandAvailability { knownAvailable, unavailable, unresolved }

class CommandPresentationEntry {
  const CommandPresentationEntry({
    required this.id,
    required this.name,
    required this.category,
    required this.activity,
    required this.description,
    required this.aliases,
    required this.source,
    required this.type,
    required this.requiredContext,
    required this.shortcut,
    required this.recommendedLocation,
    required this.availability,
  });

  final String id;
  final String name;
  final String category;
  final String activity;
  final String description;
  final List<String> aliases;
  final CommandCatalogSource source;
  final CommandCatalogEntryType type;
  final List<String> requiredContext;
  final String? shortcut;
  final String recommendedLocation;
  final CommandAvailability availability;

  Map<String, Object?> toJson() => {
    'id': id,
    'name': name,
    'category': category,
    'activity': activity,
    'description': description,
    'aliases': List<String>.from(aliases),
    'source': source.name,
    'type': type.name,
    'requiredContext': List<String>.from(requiredContext),
    'shortcut': shortcut,
    'recommendedLocation': recommendedLocation,
    'availability': availability.name,
  };

  factory CommandPresentationEntry.fromJson(Map<String, Object?> json) {
    return CommandPresentationEntry(
      id: json['id']! as String,
      name: json['name']! as String,
      category: json['category']! as String,
      activity: json['activity']! as String,
      description: json['description']! as String,
      aliases: List<String>.from(json['aliases']! as List),
      source: CommandCatalogSource.values.byName(json['source']! as String),
      type: CommandCatalogEntryType.values.byName(json['type']! as String),
      requiredContext: List<String>.from(json['requiredContext']! as List),
      shortcut: json['shortcut'] as String?,
      recommendedLocation: json['recommendedLocation']! as String,
      availability: CommandAvailability.values.byName(
        json['availability']! as String,
      ),
    );
  }
}

